const CONTROL_CHARS = { 姿: "姿勢", 物: "物の扱い", 傾: "傾きと量", 時: "タイミング", 言: "発言と視線", 順: "順序と配置" };

function splitList(s) {
  if (!s || s === "なし") return [];
  return s.split("、").map((x) => x.trim()).filter((x) => x && x !== "なし");
}

function build() {
  const canonical = parseCanonical();
  const data = { ...d0102, ...d0304, ...d0506, ...d0708, ...d0910, ...d1113 };

  // 項目ID → 入っている場面ID
  const scenariosOf = {};
  for (const sc of SCENARIOS) {
    for (const [id] of sc.items) {
      (scenariosOf[id] ||= []);
      if (!scenariosOf[id].includes(sc.id)) scenariosOf[id].push(sc.id);
    }
  }

  const items = canonical.map((c) => {
    const d = data[c.id];
    if (!d) throw new Error(`${c.id} ${c.name} の中身が item-data にありません`);
    const controls = [...d.c].map((ch) => {
      if (!CONTROL_CHARS[ch]) throw new Error(`${c.id} の操作の系統の文字が不明: ${ch}`);
      return CONTROL_CHARS[ch];
    });
    const scenarios = scenariosOf[c.id] || [];
    const failures = d.f.map(([example, reaction, recovery]) => ({ example, reaction, recovery }));
    const specReady = Boolean(d.g && d.ok && failures.length > 0);
    let status = specReady && scenarios.some((s) => SPEC_SCENARIOS.includes(s)) ? "仕様済み" : "未着手";
    // ゲームで動くことを確かめた項目（data/implementation.json）だけ、状態を上げる
    const impl = IMPL.items?.[c.id];
    if (impl) status = impl.status;
    const sources = (SOURCE_MAP[c.id] || []).map((key) => {
      const s = SOURCES[key];
      if (!s) throw new Error(`${c.id} の出典キーが不明: ${key}`);
      return { url: s.url, title: s.title, checkedOn: s.ok ? CHECKED_ON : null, status: s.ok ? "確認済み" : "未確認" };
    });
    const item = {
      id: c.id,
      name: c.name,
      category: c.category,
      kind: d.k,
      parents: d.p,
      scenarios,
      playerRole: d.r,
      controls,
      goal: d.g,
      prerequisites: d.pre,
      successCriteria: d.ok,
      failures,
      needs: { people: splitList(d.n[0]), props: splitList(d.n[1]), motions: splitList(d.n[2]), sounds: splitList(d.n[3]) },
      sources,
      variations: d.v || "未確認",
      gameExaggeration: d.x,
      status,
    };
    if (d.note) item.notes = d.note;
    return item;
  });

  const unknown = Object.keys(data).filter((id) => !canonical.some((c) => c.id === id));
  if (unknown.length) throw new Error(`正本にないIDが item-data にあります: ${unknown.join(", ")}`);

  const scenarios = SCENARIOS.map((sc) => ({
    id: sc.id,
    title: sc.title,
    status: sc.status,
    role: sc.role,
    flow: sc.flow,
    items: sc.items.map(([id, step, note]) => ({ id, step, note })),
  }));

  return {
    items: { version: 1, generatedBy: "tools/build-items.mjs", items },
    scenarios: { version: 1, generatedBy: "tools/build-items.mjs", scenarios },
  };
}

const out = build();
mkdirSync(join(ROOT, "data"), { recursive: true });
writeFileSync(join(ROOT, "data/items.json"), JSON.stringify(out.items, null, 2) + "\n");
writeFileSync(join(ROOT, "data/scenarios.json"), JSON.stringify(out.scenarios, null, 2) + "\n");
console.log(`data/items.json: ${out.items.items.length} 件 / data/scenarios.json: ${out.scenarios.scenarios.length} 場面`);
