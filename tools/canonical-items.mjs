/** @returns {{id:string,name:string,category:string,categoryNo:number}[]} */
export function parseCanonical() {
  const out = [];
  for (const line of CANONICAL_TEXT.split("\n")) {
    const m = line.match(/^(\d+)\. (.+?)（S\d{3}〜S\d{3}）: (.+)$/);
    if (!m) continue;
    const categoryNo = Number(m[1]);
    const category = m[2];
    for (const part of m[3].split("／")) {
      const pm = part.match(/^(S\d{3}) (.+)$/);
      if (!pm) throw new Error(`正本の行を読めません: ${part}`);
      out.push({ id: pm[1], name: pm[2], category, categoryNo });
    }
  }
  return out;
}

